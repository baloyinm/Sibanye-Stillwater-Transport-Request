// Turns a people CSV (see templates/people.csv) into SQL for the live MariaDB, after checking every row.
// Usage: node scripts/import.mjs --check [file]      checks only
//        node scripts/import.mjs [file] [outdir]      checks, then writes outdir/import-people.sql and outdir/temp-passwords.csv
// Default file: data/import/people.csv (kept out of git). Real data never goes in git; see MIGRATION.md.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { randomBytes, randomUUID } from 'node:crypto';
import { hashPassword } from '../lib/auth_guard.mjs';

export function parseCsv(text) {
  const rows = []; let row = [], f = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"') { if (text[i + 1] === '"') { f += '"'; i++; } else q = false; } else f += c; }
    else if (c === '"') q = true; else if (c === ',') { row.push(f); f = ''; }
    else if (c === '\n' || c === '\r') { if (c === '\r' && text[i + 1] === '\n') i++; row.push(f); f = ''; if (row.some((x) => x !== '')) rows.push(row); row = []; }
    else f += c;
  }
  if (f !== '' || row.length) { row.push(f); if (row.some((x) => x !== '')) rows.push(row); }
  const [head, ...body] = rows; return body.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] ?? '').trim()])));
}
const COLS = ['email', 'user_type', 'name', 'surname', 'z_number', 'mining_operation', 'specific_site', 'car_type', 'registration_number'];

/** Returns { problems: ['row 3: ...'], people } . Nothing is written. */
export function checkPeople(rows) {
  const problems = []; const people = []; const emails = new Set(), zs = new Set();
  rows.forEach((r, i) => {
    const n = `row ${i + 2}`;
    if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(r.email ?? '')) problems.push(`${n}: email is missing or not valid.`);
    else if (emails.has(r.email.toLowerCase())) problems.push(`${n}: this email is listed twice.`); else emails.add(r.email.toLowerCase());
    if (!['user', 'admin', 'driver'].includes(r.user_type)) problems.push(`${n}: user_type must be user, admin or driver.`);
    if (!r.name) problems.push(`${n}: name is required.`);
    if (r.z_number) { if (zs.has(r.z_number)) problems.push(`${n}: this Z number is listed twice.`); zs.add(r.z_number); }
    if (r.user_type === 'driver' && (!r.car_type || !r.registration_number)) problems.push(`${n}: a driver needs car_type and registration_number.`);
    for (const c of COLS) if ((r[c] ?? '').length > 255) problems.push(`${n}: ${c} is too long.`);
    people.push(r);
  });
  return { problems, people };
}
const q = (s) => (s === '' || s == null ? 'NULL' : `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);

export async function buildSql(people) {
  const sql = ['-- Generated by scripts/import.mjs. Contains real people when built from real data: keep out of git.', 'START TRANSACTION;']; const temps = ['email,temporary_password'];
  for (const p of people) {
    const id = randomUUID(); const temp = randomBytes(9).toString('base64url');
    sql.push(`INSERT INTO users (id,email,password_hash,user_type) VALUES (${q(id)},${q(p.email.toLowerCase())},${q(await hashPassword(temp))},${q(p.user_type)});`);
    if (p.user_type === 'driver') sql.push(`INSERT INTO drivers (id,name,surname,z_number,mining_operation,car_type,registration_number,is_available) VALUES (${q(id)},${q(p.name)},${q(p.surname)},${q(p.z_number)},${q(p.mining_operation)},${q(p.car_type)},${q(p.registration_number)},FALSE);`);
    else sql.push(`INSERT INTO profiles (id,name,surname,z_number,mining_operation,specific_site,role) VALUES (${q(id)},${q(p.name)},${q(p.surname)},${q(p.z_number)},${q(p.mining_operation)},${q(p.specific_site)},${q(p.user_type)});`);
    temps.push(`${p.email.toLowerCase()},${temp}`);
  }
  sql.push('COMMIT;'); return { sql: sql.join('\n') + '\n', temps: temps.join('\n') + '\n' };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2); const check = args.includes('--check'); const rest = args.filter((a) => !a.startsWith('--'));
  const file = rest[0] ?? 'data/import/people.csv'; const out = rest[1] ?? 'data/import/out';
  let text; try { text = readFileSync(file, 'utf8'); } catch { console.error(`Cannot read ${file}. Copy templates/people.csv to data/import/people.csv and fill it in.`); process.exit(2); }
  const { problems, people } = checkPeople(parseCsv(text));
  if (problems.length) { console.error(problems.join('\n')); console.error(`${problems.length} problem(s). Nothing written.`); process.exit(1); }
  console.log(`${people.length} row(s) checked: OK.`);
  if (!check) { const { sql, temps } = await buildSql(people); mkdirSync(out, { recursive: true }); writeFileSync(`${out}/import-people.sql`, sql); writeFileSync(`${out}/temp-passwords.csv`, temps, { mode: 0o600 }); console.log(`Wrote ${out}/import-people.sql and ${out}/temp-passwords.csv (keep both out of git; give each person their temporary password privately).`); }
}
